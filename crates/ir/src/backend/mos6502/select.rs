//! Instruction selection: IR opcodes → 6502 instructions
//!
//! Conventions:
//! - every value is 8-bit, comparisons are unsigned;
//! - the accumulator is the only register able to compute: when an operation
//!   does not target `a`, the accumulator is saved and restored around it
//!   (`pha` … `pla`), so registers hold what the source code says.
//!   The status flags are then only meaningful after operations done directly
//!   in a register;
//! - `x += 1` / `x -= 1` on `x`, `y` or memory use `inc`/`dec`, which leave the carry untouched;
//! - some sequences need a zero-page scratch byte (see [`Mos6502::scratch`](super::Mos6502::scratch)).

use super::isa::{
    Arg, Inst,
    Mnemonic::{self, *},
    Mode, Op, Target, opcode,
};
use crate::{
    backend::BackendError,
    intermediate::{
        Condition, IrFunc, JumpTarget, Label, MemCell, OpBinary, OpCode, OpCompare, OpUnary,
        Operand,
    },
    link::{Item, Section, Symbol, SymbolTable},
};
use asmanite_common::{
    number::Number,
    operator::{OpType, Operator},
    path::Path,
    register::RegIdent,
    status::StatusFlag,
};

type Result<T> = core::result::Result<T, BackendError>;

/// Registers of the 6502 (the stack pointer is not exposed)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Reg {
    A,
    X,
    Y,
}

impl Reg {
    #[inline]
    fn load(self) -> Mnemonic {
        match self {
            Self::A => Lda,
            Self::X => Ldx,
            Self::Y => Ldy,
        }
    }

    #[inline]
    fn store(self) -> Mnemonic {
        match self {
            Self::A => Sta,
            Self::X => Stx,
            Self::Y => Sty,
        }
    }

    #[inline]
    fn compare(self) -> Mnemonic {
        match self {
            Self::A => Cmp,
            Self::X => Cpx,
            Self::Y => Cpy,
        }
    }
}

/// Memory location with a known address
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Loc {
    addr: u16,

    /// Index register (`x` or `y`)
    index: Option<Reg>,

    /// Can zero-page modes be used ?
    /// With an index, the whole variable must be in zero page
    /// because zero-page indexing wraps around at $FF.
    zero_page: bool,
}

/// Resolved IR operand
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Val {
    Imm(u8),
    Reg(Reg),
    Mem(Loc),
    Stack,
}

/// Resolved jump target
#[derive(Debug, Clone, PartialEq, Eq)]
enum Dest {
    /// Direct
    Addr(Target),

    /// Through a pointer stored at this address
    Indirect(u16),
}

/// Lower one function into a section of 6502 code
pub fn select(
    func: &IrFunc,
    func_id: u32,
    symbols: &SymbolTable,
    scratch: Option<u8>,
    synthetic: &mut u32,
) -> Result<Section<Op>> {
    let mut selector = Selector {
        symbols,
        scratch,
        synthetic,
        func: &func.name,
        func_id,
        items: Vec::with_capacity(func.body.len() * 2),
    };
    for opcode in &func.body {
        selector.opcode(opcode)?;
    }
    Ok(Section {
        name: Symbol::Func(func.name.clone()),
        storage: func.storage.clone(),
        items: selector.items,
    })
}

struct Selector<'s> {
    /// Address of the variables
    symbols: &'s SymbolTable,

    /// Zero-page byte usable as a temporary
    scratch: Option<u8>,

    /// Counter for labels generated by the backend (shared by all functions)
    synthetic: &'s mut u32,

    /// Function being lowered (for error messages)
    func: &'s Path,

    /// Index of the function (for its local labels)
    func_id: u32,

    /// Generated code
    items: Vec<Item<Op>>,
}

impl Selector<'_> {
    fn opcode(&mut self, opcode: &OpCode) -> Result<()> {
        match opcode {
            OpCode::Label(label) => {
                let symbol = self.label(label);
                self.items.push(Item::Label(symbol));
                Ok(())
            }
            OpCode::Jump(target) => {
                let dest = self.dest(target)?;
                self.jump(&dest)
            }
            OpCode::Branch(branch) => {
                let dest = self.dest(&branch.target)?;
                match &branch.cond {
                    Condition::Status { flag, inverse } => {
                        let mnemonic = match flag {
                            StatusFlag::Zero => Beq,
                            StatusFlag::Negative => Bmi,
                            StatusFlag::Carry => Bcs,
                            StatusFlag::Overflow => Bvs,
                        };
                        let mnemonic = if *inverse {
                            inverse_branch(mnemonic)?
                        } else {
                            mnemonic
                        };
                        self.branch(mnemonic, &dest)
                    }
                    Condition::Compare(compare) => self.compare(compare, &dest),
                }
            }
            OpCode::Call(path) => self.inst(
                Jsr,
                Mode::Absolute,
                Arg::Word(Target::Symbol(Symbol::Func(path.clone()))),
            ),
            OpCode::Return => self.implied(Rts),
            OpCode::Transfer(transfer) => {
                let dst = self.val(&transfer.dst)?;
                let src = self.val(&transfer.src)?;
                self.transfer(dst, src)
            }
            OpCode::Unary(unary) => self.unary(unary),
            OpCode::Binary(binary) => self.binary(binary),
        }
    }

    // MARK: Errors

    fn unsupported<T>(&self, what: impl Into<String>) -> Result<T> {
        Err(BackendError::Unsupported {
            at: self.func.clone(),
            what: what.into(),
        })
    }

    fn out_of_range(&self, what: &'static str, value: Number) -> BackendError {
        BackendError::OutOfRange {
            at: self.func.clone(),
            what,
            value,
        }
    }

    /// Zero-page scratch byte, required by the given operation
    fn scratch(&self, what: &'static str) -> Result<Loc> {
        self.scratch
            .map(|addr| Loc {
                addr: u16::from(addr),
                index: None,
                zero_page: true,
            })
            .ok_or_else(|| BackendError::NeedsScratch {
                at: self.func.clone(),
                what,
            })
    }

    // MARK: Operands

    fn val(&self, operand: &Operand) -> Result<Val> {
        match operand {
            Operand::Imm(value) => self.imm(*value).map(Val::Imm),
            Operand::Reg(reg) => self.reg(reg).map(Val::Reg),
            Operand::Mem(cell) => self.loc(cell).map(Val::Mem),
            Operand::Stack => Ok(Val::Stack),
        }
    }

    /// Signed or unsigned byte
    fn imm(&self, value: Number) -> Result<u8> {
        u8::try_from(value).map_err(|_| self.out_of_range("an 8-bits value", value))
    }

    fn reg(&self, reg: &RegIdent) -> Result<Reg> {
        for (name, value) in [("a", Reg::A), ("x", Reg::X), ("y", Reg::Y)] {
            if *reg == RegIdent::new(name) {
                return Ok(value);
            }
        }
        self.unsupported(format!("register `{reg}`"))
    }

    fn loc(&self, cell: &MemCell) -> Result<Loc> {
        let symbol = Symbol::Var(cell.var.clone());
        let base = self.symbols.resolve(&symbol)?;
        let size = self.symbols.size(&symbol).unwrap_or(1);

        let addr = base as i64 + cell.offset;
        let addr =
            u16::try_from(addr).map_err(|_| self.out_of_range("a 16-bit address", addr.into()))?;

        let index = match cell.index {
            None => None,
            Some(reg) => match self.reg(&reg)? {
                Reg::A => return self.unsupported("indexing with the accumulator"),
                reg => Some(reg),
            },
        };
        let zero_page = match index {
            None => addr <= 0xFF,
            Some(_) => base + size <= 0x100,
        };
        Ok(Loc {
            addr,
            index,
            zero_page,
        })
    }

    fn label(&self, label: &Label) -> Symbol {
        match label {
            Label::Local(id) => Symbol::Local {
                func: self.func_id,
                label: *id,
            },
            Label::Named(path) => Symbol::Label(path.clone()),
        }
    }

    fn new_label(&mut self) -> Symbol {
        let symbol = Symbol::Synthetic(*self.synthetic);
        *self.synthetic += 1;
        symbol
    }

    fn dest(&self, target: &JumpTarget) -> Result<Dest> {
        match target {
            JumpTarget::Label(label) => Ok(Dest::Addr(Target::Symbol(self.label(label)))),
            JumpTarget::Address(addr) => u16::try_from(*addr)
                .map(|addr| Dest::Addr(Target::Addr(addr)))
                .map_err(|_| self.out_of_range("a 16-bit address", (*addr).into())),
            JumpTarget::Indirect(pointer) => match self.val(pointer)? {
                Val::Mem(Loc {
                    addr, index: None, ..
                }) => {
                    if addr & 0xFF == 0xFF {
                        // `jmp ($xxFF)` reads the high byte from $xx00
                        self.unsupported("an indirect jump through a pointer at the end of a page")
                    } else {
                        Ok(Dest::Indirect(addr))
                    }
                }
                _ => self.unsupported("an indirect jump through something else than a variable"),
            },
            JumpTarget::Relative(_) => self.unsupported("a relative jump target"),
            JumpTarget::Scope(_) => self.unsupported("a jump to a scope"),
        }
    }

    // MARK: Emission

    fn push(&mut self, inst: Inst) {
        self.items.push(Item::Inst(Op::Inst(inst)));
    }

    fn inst(&mut self, mnemonic: Mnemonic, mode: Mode, arg: Arg) -> Result<()> {
        let inst = Inst::new(mnemonic, mode, arg).ok_or_else(|| {
            BackendError::Internal(format!("invalid instruction `{mnemonic}` in mode {mode:?}"))
        })?;
        self.push(inst);
        Ok(())
    }

    #[inline]
    fn implied(&mut self, mnemonic: Mnemonic) -> Result<()> {
        self.inst(mnemonic, Mode::Implied, Arg::None)
    }

    #[inline]
    fn on_acc(&mut self, mnemonic: Mnemonic) -> Result<()> {
        self.inst(mnemonic, Mode::Accumulator, Arg::None)
    }

    #[inline]
    fn immediate(&mut self, mnemonic: Mnemonic, value: u8) -> Result<()> {
        self.inst(mnemonic, Mode::Immediate, Arg::Byte(value))
    }

    /// Instruction accessing memory, if the CPU has a suitable addressing mode.
    /// Zero-page modes are preferred.
    fn mem_inst(mnemonic: Mnemonic, loc: Loc) -> Option<Inst> {
        let (zero_page, absolute) = match loc.index {
            None => (Mode::ZeroPage, Mode::Absolute),
            Some(Reg::X) => (Mode::ZeroPageX, Mode::AbsoluteX),
            Some(_) => (Mode::ZeroPageY, Mode::AbsoluteY),
        };
        if loc.zero_page && opcode(mnemonic, zero_page).is_some() {
            Inst::new(mnemonic, zero_page, Arg::Byte(loc.addr as u8))
        } else {
            Inst::new(mnemonic, absolute, Arg::Word(Target::Addr(loc.addr)))
        }
    }

    /// Emit an instruction with an immediate or memory operand.
    /// Return `false` if the CPU has no suitable addressing mode.
    fn try_val(&mut self, mnemonic: Mnemonic, val: Val) -> bool {
        let inst = match val {
            Val::Imm(value) => Inst::new(mnemonic, Mode::Immediate, Arg::Byte(value)),
            Val::Mem(loc) => Self::mem_inst(mnemonic, loc),
            Val::Reg(_) | Val::Stack => None,
        };
        inst.map(|inst| self.push(inst)).is_some()
    }

    /// Emit an instruction with an immediate or memory operand which must be supported
    fn operate(&mut self, mnemonic: Mnemonic, val: Val) -> Result<()> {
        if self.try_val(mnemonic, val) {
            Ok(())
        } else {
            Err(BackendError::Internal(format!(
                "no addressing mode of `{mnemonic}` for {val:?}"
            )))
        }
    }

    // MARK: Transfers

    fn reg_to_reg(&mut self, dst: Reg, src: Reg) -> Result<()> {
        match (dst, src) {
            _ if dst == src => Ok(()),
            (Reg::X, Reg::A) => self.implied(Tax),
            (Reg::Y, Reg::A) => self.implied(Tay),
            (Reg::A, Reg::X) => self.implied(Txa),
            (Reg::A, Reg::Y) => self.implied(Tya),
            // between X and Y
            _ => match self.scratch("moving data between `x` and `y`") {
                Ok(scratch) => {
                    self.store(src, scratch)?;
                    self.load(dst, Val::Mem(scratch))
                }
                Err(_) => {
                    self.implied(Pha)?;
                    self.reg_to_reg(Reg::A, src)?;
                    self.reg_to_reg(dst, Reg::A)?;
                    self.implied(Pla)
                }
            },
        }
    }

    /// Load a register from an immediate value or memory
    fn load(&mut self, reg: Reg, val: Val) -> Result<()> {
        if self.try_val(reg.load(), val) {
            return Ok(());
        }
        // `ldx abs,x` and `ldy abs,y` do not exist
        if reg == Reg::A {
            return self.operate(Lda, val);
        }
        self.implied(Pha)?;
        self.operate(Lda, val)?;
        self.reg_to_reg(reg, Reg::A)?;
        self.implied(Pla)
    }

    /// Store a register in memory
    fn store(&mut self, reg: Reg, loc: Loc) -> Result<()> {
        if self.try_val(reg.store(), Val::Mem(loc)) {
            return Ok(());
        }
        // `stx` and `sty` have neither absolute indexed modes nor self-indexing
        self.implied(Pha)?;
        self.reg_to_reg(Reg::A, reg)?;
        self.operate(Sta, Val::Mem(loc))?;
        self.implied(Pla)
    }

    /// Write any operand into a register
    fn read_into(&mut self, reg: Reg, src: Val) -> Result<()> {
        match src {
            Val::Reg(src) => self.reg_to_reg(reg, src),
            Val::Imm(_) | Val::Mem(_) => self.load(reg, src),
            Val::Stack if reg == Reg::A => self.implied(Pla),
            Val::Stack => {
                let scratch = self.scratch("pulling `x` or `y` from the stack")?;
                self.store(Reg::A, scratch)?;
                self.implied(Pla)?;
                self.reg_to_reg(reg, Reg::A)?;
                self.load(Reg::A, Val::Mem(scratch))
            }
        }
    }

    /// Write a register into any assignable operand
    fn write_from(&mut self, reg: Reg, dst: Val) -> Result<()> {
        match dst {
            Val::Reg(dst) => self.reg_to_reg(dst, reg),
            Val::Mem(loc) => self.store(reg, loc),
            Val::Stack if reg == Reg::A => self.implied(Pha),
            Val::Stack => {
                let scratch = self.scratch("pushing `x` or `y` on the stack")?;
                self.store(Reg::A, scratch)?;
                self.reg_to_reg(Reg::A, reg)?;
                self.implied(Pha)?;
                self.load(Reg::A, Val::Mem(scratch))
            }
            Val::Imm(_) => self.unsupported("writing into an immediate value"),
        }
    }

    fn transfer(&mut self, dst: Val, src: Val) -> Result<()> {
        if dst == src {
            return Ok(());
        }
        match (dst, src) {
            (Val::Imm(_), _) => self.unsupported("writing into an immediate value"),
            (Val::Reg(dst), _) => self.read_into(dst, src),
            (_, Val::Reg(src)) => self.write_from(src, dst),
            // Memory or stack on both sides: through the accumulator
            (Val::Stack, _) | (_, Val::Stack) => {
                let scratch = self.scratch("moving data between memory and the stack")?;
                self.store(Reg::A, scratch)?;
                self.read_into(Reg::A, src)?;
                self.write_from(Reg::A, dst)?;
                self.load(Reg::A, Val::Mem(scratch))
            }
            _ => {
                self.implied(Pha)?;
                self.read_into(Reg::A, src)?;
                self.write_from(Reg::A, dst)?;
                self.implied(Pla)
            }
        }
    }

    // MARK: Operations

    /// Load `src` in the accumulator, apply `body`, write the accumulator in `dst`.
    /// The accumulator is preserved if it is not the destination.
    fn via_acc(
        &mut self,
        dst: Val,
        src: Val,
        body: impl FnOnce(&mut Self) -> Result<()>,
    ) -> Result<()> {
        if dst == Val::Stack || src == Val::Stack {
            return self.unsupported("the stack as operand of an operation");
        }
        let save = dst != Val::Reg(Reg::A);
        if save {
            self.implied(Pha)?;
        }
        self.read_into(Reg::A, src)?;
        body(self)?;
        self.write_from(Reg::A, dst)?;
        if save {
            self.implied(Pla)?;
        }
        Ok(())
    }

    /// Operand usable by `adc`, `cmp`, ...: immediate or memory.
    /// A register is first copied in the scratch byte.
    fn alu_operand(&mut self, val: Val) -> Result<Val> {
        match val {
            Val::Imm(_) | Val::Mem(_) => Ok(val),
            Val::Reg(reg) => {
                let scratch = self.scratch("an operation with a register as right operand")?;
                self.store(reg, scratch)?;
                Ok(Val::Mem(scratch))
            }
            Val::Stack => self.unsupported("the stack as right operand"),
        }
    }

    /// Increment or decrement in place
    fn step(&mut self, dst: Val, inc: bool) -> Result<()> {
        match dst {
            Val::Reg(Reg::X) => self.implied(if inc { Inx } else { Dex }),
            Val::Reg(Reg::Y) => self.implied(if inc { Iny } else { Dey }),
            Val::Reg(Reg::A) if inc => {
                self.implied(Clc)?;
                self.immediate(Adc, 1)
            }
            Val::Reg(Reg::A) => {
                self.implied(Sec)?;
                self.immediate(Sbc, 1)
            }
            Val::Mem(loc) => match Self::mem_inst(if inc { Inc } else { Dec }, loc) {
                Some(inst) => {
                    self.push(inst);
                    Ok(())
                }
                // no `inc abs,y`
                None => self.via_acc(dst, dst, |s| s.step(Val::Reg(Reg::A), inc)),
            },
            Val::Imm(_) | Val::Stack => {
                self.unsupported("incrementing an immediate value or the stack")
            }
        }
    }

    fn unary(&mut self, unary: &OpUnary) -> Result<()> {
        let dst = self.val(&unary.dst)?;
        let src = self.val(&unary.src)?;
        match unary.op.op_type {
            OpType::Add => self.transfer(dst, src),
            OpType::Inc | OpType::Dec => {
                self.transfer(dst, src)?;
                self.step(dst, unary.op.op_type == OpType::Inc)
            }
            OpType::BitInv => self.via_acc(dst, src, |s| s.immediate(Eor, 0xFF)),
            OpType::Sub => self.via_acc(dst, src, |s| {
                s.immediate(Eor, 0xFF)?;
                s.implied(Clc)?;
                s.immediate(Adc, 1)
            }),
            other => self.unsupported(format!("the unary operator `{other}`")),
        }
    }

    fn binary(&mut self, binary: &OpBinary) -> Result<()> {
        let op = binary.op;
        let dst = self.val(&binary.dst)?;
        let mut lhs = self.val(&binary.lhs)?;
        let mut rhs = self.val(&binary.rhs)?;

        let mnemonic = match op.op_type {
            OpType::Add => Adc,
            OpType::Sub => Sbc,
            OpType::BitAnd => And,
            OpType::BitOr => Ora,
            OpType::BitXor => Eor,
            OpType::ShL | OpType::ShRA | OpType::ShRL | OpType::RotL | OpType::RotR => {
                return self.shift(op, dst, lhs, rhs);
            }
            OpType::Mul | OpType::Div | OpType::Rem => {
                return self.unsupported(format!("the operator `{op}` (needs a runtime routine)"));
            }
            other => return self.unsupported(format!("the binary operator `{other}`")),
        };

        // `x += 1` and `x -= 1`
        let add_sub = matches!(op.op_type, OpType::Add | OpType::Sub);
        if add_sub
            && !op.carry
            && dst == lhs
            && rhs == Val::Imm(1)
            && !matches!(dst, Val::Reg(Reg::A) | Val::Stack)
        {
            return self.step(dst, op.op_type == OpType::Add);
        }

        // Only the accumulator computes: prefer having it on the left
        if rhs == Val::Reg(Reg::A) && lhs != Val::Reg(Reg::A) && op.op_type != OpType::Sub {
            core::mem::swap(&mut lhs, &mut rhs);
        }
        let rhs = self.alu_operand(rhs)?;

        self.via_acc(dst, lhs, |s| {
            match op.op_type {
                OpType::Add if !op.carry => s.implied(Clc)?,
                OpType::Sub if !op.carry => s.implied(Sec)?,
                _ => {}
            }
            s.operate(mnemonic, rhs)
        })
    }

    fn shift(&mut self, op: Operator, dst: Val, lhs: Val, rhs: Val) -> Result<()> {
        /// One step of the shift
        #[derive(Clone, Copy)]
        enum Step {
            /// Single instruction, also available on memory
            Simple(Mnemonic),
            /// Arithmetic shift right
            Arith,
            /// 8-bit rotation (without the carry)
            RotL8,
            RotR8,
        }

        let Val::Imm(amount) = rhs else {
            return self.unsupported("a shift by a non-constant amount");
        };
        let amount = u32::from(amount);
        let (step, count) = match (op.op_type, op.carry) {
            (OpType::ShL, _) => (Step::Simple(Asl), amount.min(8)),
            (OpType::ShRL, _) => (Step::Simple(Lsr), amount.min(8)),
            (OpType::ShRA, _) => (Step::Arith, amount.min(8)),
            (OpType::RotL, true) => (Step::Simple(Rol), amount % 9),
            (OpType::RotR, true) => (Step::Simple(Ror), amount % 9),
            (OpType::RotL, false) => (Step::RotL8, amount % 8),
            (OpType::RotR, false) => (Step::RotR8, amount % 8),
            _ => return Err(BackendError::Internal(format!("`{op}` is not a shift"))),
        };
        if count == 0 {
            return self.transfer(dst, lhs);
        }

        // In place on memory
        if let (Step::Simple(mnemonic), Val::Mem(loc)) = (step, dst)
            && dst == lhs
            && let Some(inst) = Self::mem_inst(mnemonic, loc)
        {
            for _ in 0..count {
                self.push(inst.clone());
            }
            return Ok(());
        }

        self.via_acc(dst, lhs, |s| {
            for _ in 0..count {
                match step {
                    Step::Simple(mnemonic) => s.on_acc(mnemonic)?,
                    // carry = sign bit, then shift it in
                    Step::Arith => {
                        s.immediate(Cmp, 0x80)?;
                        s.on_acc(Ror)?;
                    }
                    // bit 7 goes in the carry, then in bit 0
                    Step::RotL8 => {
                        s.on_acc(Asl)?;
                        s.immediate(Adc, 0)?;
                    }
                    // bit 0 goes in the carry, then in bit 7
                    Step::RotR8 => {
                        s.implied(Pha)?;
                        s.on_acc(Lsr)?;
                        s.implied(Pla)?;
                        s.on_acc(Ror)?;
                    }
                }
            }
            Ok(())
        })
    }

    // MARK: Control flow

    fn jump(&mut self, dest: &Dest) -> Result<()> {
        match dest {
            Dest::Addr(target) => self.inst(Jmp, Mode::Absolute, Arg::Word(target.clone())),
            Dest::Indirect(addr) => self.inst(Jmp, Mode::Indirect, Arg::Word(Target::Addr(*addr))),
        }
    }

    /// Conditional branch
    fn branch(&mut self, mnemonic: Mnemonic, dest: &Dest) -> Result<()> {
        match dest {
            Dest::Addr(target) => {
                self.items.push(Item::Inst(Op::Branch {
                    mnemonic,
                    target: target.clone(),
                    long: false,
                }));
                Ok(())
            }
            Dest::Indirect(_) => {
                let skip = self.new_label();
                self.branch(
                    inverse_branch(mnemonic)?,
                    &Dest::Addr(Target::Symbol(skip.clone())),
                )?;
                self.jump(dest)?;
                self.items.push(Item::Label(skip));
                Ok(())
            }
        }
    }

    fn compare(&mut self, compare: &OpCompare, dest: &Dest) -> Result<()> {
        let mut op = compare.op.op_type;
        let mut lhs = self.val(&compare.lhs)?;
        let mut rhs = self.val(&compare.rhs)?;
        if !op.is_comparison() {
            return self.unsupported(format!("the comparison operator `{op}`"));
        }

        // Known at compile time
        if let (Val::Imm(lhs), Val::Imm(rhs)) = (lhs, rhs) {
            if op.eval_compare(lhs, rhs) == Some(true) {
                self.jump(dest)?;
            }
            return Ok(());
        }

        // The 6502 compares a register with an operand:
        // put the register, or else the memory, on the left.
        let rank = |val: Val| match val {
            Val::Reg(_) => 0,
            Val::Mem(_) | Val::Stack => 1,
            Val::Imm(_) => 2,
        };
        if rank(rhs) < rank(lhs) {
            core::mem::swap(&mut lhs, &mut rhs);
            op = mirror(op);
        }

        // `>` and `<=` need two branches: with a constant, use `>=` and `<` instead
        if let Val::Imm(value) = rhs {
            match (op, value) {
                (OpType::Gt, 0xFF) => return Ok(()),
                (OpType::LEq, 0xFF) => return self.jump(dest),
                (OpType::Gt, _) => (op, rhs) = (OpType::GEq, Val::Imm(value + 1)),
                (OpType::LEq, _) => (op, rhs) = (OpType::Lt, Val::Imm(value + 1)),
                _ => {}
            }
        }

        match lhs {
            Val::Reg(reg) => {
                let rhs = self.alu_operand(rhs)?;
                // `cpx` and `cpy` have no indexed modes
                if !self.try_val(reg.compare(), rhs) {
                    self.compare_in_acc(lhs, rhs)?;
                }
            }
            _ => self.compare_in_acc(lhs, rhs)?,
        }

        match op {
            OpType::Eq => self.branch(Beq, dest),
            OpType::Diff => self.branch(Bne, dest),
            OpType::Lt => self.branch(Bcc, dest),
            OpType::GEq => self.branch(Bcs, dest),
            OpType::LEq => {
                self.branch(Bcc, dest)?;
                self.branch(Beq, dest)
            }
            _ => {
                // `>`: neither equal nor lesser
                let skip = self.new_label();
                self.branch(Beq, &Dest::Addr(Target::Symbol(skip.clone())))?;
                self.branch(Bcs, dest)?;
                self.items.push(Item::Label(skip));
                Ok(())
            }
        }
    }

    /// Compare `lhs` with `rhs` using the accumulator, which is preserved.
    /// The flags of the comparison are kept with `php` / `plp`.
    fn compare_in_acc(&mut self, lhs: Val, rhs: Val) -> Result<()> {
        let rhs = self.alu_operand(rhs)?;
        let scratch = self.scratch("comparing memory or an index register with memory")?;
        self.store(Reg::A, scratch)?;
        self.read_into(Reg::A, lhs)?;
        self.operate(Cmp, rhs)?;
        self.implied(Php)?;
        self.load(Reg::A, Val::Mem(scratch))?;
        self.implied(Plp)
    }
}

/// Opposite branch
fn inverse_branch(mnemonic: Mnemonic) -> Result<Mnemonic> {
    mnemonic
        .inverse_branch()
        .ok_or_else(|| BackendError::Internal(format!("`{mnemonic}` is not a branch")))
}

/// Comparison holding when the operands are swapped
fn mirror(op: OpType) -> OpType {
    match op {
        OpType::Lt => OpType::Gt,
        OpType::Gt => OpType::Lt,
        OpType::LEq => OpType::GEq,
        OpType::GEq => OpType::LEq,
        other => other,
    }
}
