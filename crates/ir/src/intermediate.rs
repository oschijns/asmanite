use crate::{Addr, LabelId, RelAddr};
use asmanite_common::{
    ToBox, ident::Ident, number::Number, operator::Operator, path::Path, register::RegIdent,
    scope::ScopeId, status::StatusFlag,
};

/// Program to transform into CPU target instructions
#[derive(Debug, Clone, PartialEq)]
pub struct IrProgram {
    /// Memory cells to reserve that are not owned by a function
    /// (static variables, memory of the inline functions)
    pub data: Vec<IrData>,

    /// Code run by the target system at startup, before anything else.
    /// It computes the initial value of the static variables.
    pub init: IrFunc,

    /// Functions to convert
    pub functions: Vec<IrFunc>,
}

/// Memory reserved for a variable
#[derive(Debug, Clone, PartialEq)]
pub struct IrData {
    /// Absolute path of the variable
    pub name: Path,

    /// Size of the variable in bytes
    pub size: u32,

    /// Where to place the variable
    pub storage: IrStorage,
}

/// Placement of a memory cell or a function.
/// The placement is always explicit: the compiler never chooses it.
#[derive(Debug, Clone, PartialEq)]
pub enum IrStorage {
    /// Startup routine (initialize static variables)
    Startup,

    /// Place it somewhere in the given memory bank
    Bank(Ident),

    /// Place it at a fixed address
    Addr(Addr),

    /// Place it on the stack
    Stack,
}

/// Define a function which should be placed somewhere in the ROM
#[derive(Debug, Clone, PartialEq)]
pub struct IrFunc {
    /// Absolute path of the function
    pub name: Path,

    /// Where to place the code of the function.
    /// Inline functions do not appear in the IR: they are expanded at each call site.
    pub storage: IrStorage,

    /// Location of each parameter, in declaration order.
    /// The caller writes the arguments in these locations before the call.
    pub params: Vec<Operand>,

    /// Location of the return value, if any.
    /// The callee writes its result there before returning.
    pub ret: Option<Operand>,

    /// Memory cells owned by the function (memory parameters, return value, locals)
    pub locals: Vec<IrData>,

    /// Instructions of the function
    pub body: Vec<OpCode>,
}

/// Define a generic instruction
#[derive(Debug, Clone, PartialEq)]
pub enum OpCode {
    /// Define a label at this position (emits no instruction)
    Label(Label),

    /// Unconditional jump
    Jump(JumpTarget),

    /// Branching operation
    Branch(Box<OpBranch>),

    /// Call a function
    Call(Path),

    /// Return from the current function
    Return,

    /// Transfer data between two operands
    Transfer(Box<OpTransfer>),

    /// Apply operation to operand
    Unary(Box<OpUnary>),

    /// Apply operation between two operand
    Binary(Box<OpBinary>),
}

/// A position in the code that can be jumped to
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum Label {
    /// Label generated by the compiler
    Local(LabelId),

    /// Label written by the user (`'label:`)
    Named(Path),
}

/// Define a branching instruction
#[derive(Debug, Clone, PartialEq)]
pub struct OpBranch {
    /// Condition to branch on
    pub cond: Condition,

    /// Target to branch to
    pub target: JumpTarget,
}

impl ToBox for OpBranch {}

/// Condition in a branching operation
#[derive(Debug, Clone, PartialEq)]
pub enum Condition {
    /// Condition on a CPU status flag
    Status {
        /// Flag to check
        flag: StatusFlag,

        /// Should the condition be inversed ?
        inverse: bool,
    },

    /// Branch if the comparison between two operands holds
    Compare(Box<OpCompare>),
}

/// Comparison between two operands (`==`, `!=`, `<`, `>`, `<=`, `>=`)
#[derive(Debug, Clone, PartialEq)]
pub struct OpCompare {
    /// Relational operator
    pub op: Operator,

    /// Left operand
    pub lhs: Operand,

    /// Right operand
    pub rhs: Operand,
}

impl ToBox for OpCompare {}

/// Define the target of a jump or branch instruction
#[derive(Debug, Clone, PartialEq)]
pub enum JumpTarget {
    /// Reference to a named label.
    Scope(ScopeId),

    /// Label
    Label(Label),

    /// Reference to a known absolute address.
    Address(Addr),

    /// Relative displacement from the current instruction.
    Relative(RelAddr),

    /// Address held in a register or memory location.
    Indirect(Box<Operand>),
}

/// Transfer data from one memory operand to an other
#[derive(Debug, Clone, PartialEq)]
pub struct OpTransfer {
    /// Move data to destination
    pub dst: Operand,

    /// Move data from source
    pub src: Operand,
}

impl ToBox for OpTransfer {}

/// Unary operation on an operand
#[derive(Debug, Clone, PartialEq)]
pub struct OpUnary {
    /// Operation
    pub op: Operator,

    /// Destination operand
    pub dst: Operand,

    /// Operand
    pub src: Operand,
}

impl ToBox for OpUnary {}

/// Binary operation on two operands
#[derive(Debug, Clone, PartialEq)]
pub struct OpBinary {
    /// Operation
    pub op: Operator,

    /// Destination operand
    pub dst: Operand,

    /// Operand
    pub lhs: Operand,

    /// Operand
    pub rhs: Operand,
}

impl ToBox for OpBinary {}

// MARK: Memory

/// Define a type of memory location
#[derive(Debug, Clone, PartialEq)]
pub enum Operand {
    /// Immediate value
    Imm(Number),

    /// CPU register
    Reg(RegIdent),

    /// Path to a variable stored in RAM
    Mem(Box<MemCell>),

    /// Stack
    Stack,
}

impl Operand {
    /// Memory operand pointing at the start of a variable
    #[inline]
    pub fn mem(var: Path) -> Self {
        Self::Mem(MemCell::new(var).to_box())
    }
}

/// Define memory access in RAM
#[derive(Debug, Clone, PartialEq)]
pub struct MemCell {
    /// Name of the variable
    pub var: Path,

    /// Is there a constant offset from the variable ?
    pub offset: i64,

    /// Register used for runtime indexing
    pub index: Option<RegIdent>,
}

impl MemCell {
    /// Access the start of a variable
    #[inline]
    pub fn new(var: Path) -> Self {
        Self {
            var,
            offset: 0,
            index: None,
        }
    }
}

impl ToBox for MemCell {}
