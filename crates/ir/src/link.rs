//! Target-independent part of a backend:
//! memory map, allocation of the variables, symbol table,
//! iterative layout of the code (branch relaxation) and generation of the image.
//!
//! A backend only has to provide its instructions (implementing [`Instruction`])
//! and the instruction selection turning each [`IrFunc`](crate::inter::IrFunc)
//! into a [`Section`].

use crate::{
    Addr, LabelId,
    backend::BackendError,
    intermediate::{IrData, IrStorage},
};
use asmanite_common::{ident::Ident, path::Path};
use bytes::{Bytes, BytesMut};
use core::fmt::{self, Write as _};
use std::collections::{HashMap, HashSet};

/// Result type used when converting the IR into the backend code
type Result<T> = core::result::Result<T, BackendError>;

// MARK: Symbols

/// Anything that has an address once the program is laid out
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum Symbol {
    /// Variable (static, local or parameter)
    Var(Path),

    /// Entry point of a function
    Func(Path),

    /// Label written by the user
    Label(Path),

    /// Label generated by the translator (unique within a function)
    Local { func: LabelId, label: LabelId },

    /// Label generated by the backend
    Synthetic(LabelId),
}

impl fmt::Display for Symbol {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Var(path) | Self::Func(path) | Self::Label(path) => path.fmt(f),
            Self::Local { func, label } => write!(f, "@f{func}_l{label}"),
            Self::Synthetic(id) => write!(f, "@s{id}"),
        }
    }
}

/// Address (and size, for variables) of every symbol
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SymbolTable {
    addrs: HashMap<Symbol, Addr>,
    sizes: HashMap<Symbol, Addr>,
}

impl SymbolTable {
    /// Address of a symbol, if it is already known
    #[inline]
    pub fn get(&self, symbol: &Symbol) -> Option<Addr> {
        self.addrs.get(symbol).copied()
    }

    /// Address of a symbol which must be defined
    #[inline]
    pub fn resolve(&self, symbol: &Symbol) -> Result<Addr> {
        self.get(symbol)
            .ok_or_else(|| BackendError::Undefined(symbol.clone()))
    }

    /// Size in bytes of a variable
    #[inline]
    pub fn size(&self, symbol: &Symbol) -> Option<Addr> {
        self.sizes.get(symbol).copied()
    }

    /// Iterate over every symbol and its address
    #[inline]
    pub fn iter(&self) -> impl Iterator<Item = (&Symbol, Addr)> {
        self.addrs.iter().map(|(symbol, addr)| (symbol, *addr))
    }

    /// Set the address of a symbol. Return `true` if it changed.
    fn set(&mut self, symbol: &Symbol, addr: Addr) -> bool {
        self.addrs.insert(symbol.clone(), addr) != Some(addr)
    }
}

// MARK: Memory map

/// Can the CPU write in a memory bank ?
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BankKind {
    /// Read-only: its content is part of the generated image
    Rom,

    /// Read-write: only reserved, nothing is generated
    Ram,
}

/// Range of the address space in which code and variables can be placed
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Bank {
    /// Name used by the source code (`in <name>`)
    pub name: Ident,

    /// First address of the bank
    pub start: Addr,

    /// Size of the bank in bytes
    pub size: Addr,

    /// ROM or RAM
    pub kind: BankKind,
}

impl Bank {
    /// New bank
    #[inline]
    pub fn new(name: &str, start: Addr, size: Addr, kind: BankKind) -> Self {
        Self {
            name: Ident::new(name),
            start,
            size,
            kind,
        }
    }

    /// Address right after the bank
    #[inline]
    pub fn end(&self) -> Addr {
        self.start + self.size
    }

    /// Does the bank contain this address ?
    #[inline]
    pub fn contains(&self, addr: Addr) -> bool {
        (self.start..self.end()).contains(&addr)
    }
}

/// Memory layout of the target system
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MemoryMap {
    /// Available banks
    pub banks: Vec<Bank>,

    /// Bank receiving the startup routine
    pub startup: Ident,

    /// Value of the unused bytes of a ROM bank
    pub fill: u8,
}

impl MemoryMap {
    /// Index of a bank given its name
    fn bank(&self, name: &Ident) -> Result<usize> {
        self.banks
            .iter()
            .position(|bank| &bank.name == name)
            .ok_or_else(|| BackendError::UnknownBank(name.clone()))
    }

    /// Where to place something given its storage
    fn placement(&self, storage: &IrStorage, at: &Path) -> Result<Placement> {
        match storage {
            IrStorage::Startup => self.bank(&self.startup).map(Placement::Bank),
            IrStorage::Bank(name) => self.bank(name).map(Placement::Bank),
            IrStorage::Addr(addr) => Ok(Placement::Fixed(*addr)),
            IrStorage::Stack => Err(BackendError::Unsupported {
                at: at.clone(),
                what: "placement on the stack".to_owned(),
            }),
        }
    }
}

/// Resolved storage
#[derive(Debug, Clone, Copy)]
enum Placement {
    /// Next free address of the bank at this index
    Bank(usize),

    /// Fixed address
    Fixed(Addr),
}

// MARK: Data

/// Variables placed in memory, before laying out the code
#[derive(Debug, Clone)]
pub struct Layout {
    /// Address of every variable
    pub symbols: SymbolTable,

    /// Next free address in each bank
    cursors: Vec<Addr>,
}

/// Give an address to every variable.
/// Variables are placed in memory before the code, so that the instruction
/// selection knows their address (on the 6502, it selects zero-page modes).
pub fn allocate<'d>(map: &MemoryMap, data: impl IntoIterator<Item = &'d IrData>) -> Result<Layout> {
    let mut symbols = SymbolTable::default();
    let mut cursors: Vec<Addr> = map.banks.iter().map(|bank| bank.start).collect();

    for var in data {
        let symbol = Symbol::Var(var.name.clone());
        let size = Addr::from(var.size);
        let addr = match map.placement(&var.storage, &var.name)? {
            Placement::Fixed(addr) => addr,
            Placement::Bank(index) => {
                let addr = cursors[index];
                cursors[index] += size;
                check_bank(&map.banks[index], cursors[index])?;
                addr
            }
        };
        if symbols.addrs.contains_key(&symbol) {
            return Err(BackendError::Duplicate(symbol));
        }
        symbols.set(&symbol, addr);
        symbols.sizes.insert(symbol, size);
    }

    Ok(Layout { symbols, cursors })
}

/// Error if `end` is past the end of the bank
fn check_bank(bank: &Bank, end: Addr) -> Result<()> {
    if end > bank.end() {
        Err(BackendError::BankOverflow {
            bank: bank.name.clone(),
            excess: end - bank.end(),
        })
    } else {
        Ok(())
    }
}

// MARK: Code

/// Machine instruction of a given target
pub trait Instruction {
    /// Size in bytes of the instruction placed at `pc`.
    ///
    /// Symbols may be unknown (forward references in the first pass) or
    /// still move. An instruction can depend on them (e.g. short or long
    /// branch), but it must never shrink back once it grew: this guarantees
    /// that the layout converges.
    fn size(&mut self, pc: Addr, symbols: &SymbolTable) -> usize;

    /// Encode the instruction placed at `pc`.
    /// It must write exactly the number of bytes given by the last call to [`Self::size`].
    fn encode(&self, pc: Addr, symbols: &SymbolTable, out: &mut BytesMut) -> Result<()>;
}

/// Element of a section of code
#[derive(Debug, Clone, PartialEq)]
pub enum Item<I> {
    /// Gives the current address to a symbol
    Label(Symbol),

    /// Machine instruction
    Inst(I),
}

/// Block of code placed contiguously in memory (a function)
#[derive(Debug, Clone, PartialEq)]
pub struct Section<I> {
    /// Symbol defined at the start of the section
    pub name: Symbol,

    /// Where to place the section
    pub storage: IrStorage,

    /// Content
    pub items: Vec<Item<I>>,
}

/// Content of a ROM bank
#[derive(Debug, Clone, PartialEq)]
pub struct BankImage {
    /// Name of the bank
    pub name: Ident,

    /// Address of the first byte
    pub start: Addr,

    /// Content of the whole bank
    pub bytes: Bytes,
}

/// Result of a backend
#[derive(Debug, Clone, PartialEq)]
pub struct Image {
    /// Content of every ROM bank, in the order of the memory map
    pub banks: Vec<BankImage>,

    /// Address of every variable, function and label
    pub symbols: SymbolTable,
}

/// Maximum number of layout passes
const MAX_PASSES: usize = 64;

/// Lay out the sections after the variables, then encode them.
pub fn link<I: Instruction>(
    map: &MemoryMap,
    layout: Layout,
    mut sections: Vec<Section<I>>,
) -> Result<Image> {
    let Layout {
        mut symbols,
        cursors: data_end,
    } = layout;

    let placements = sections
        .iter()
        .map(|section| map.placement(&section.storage, section_path(&section.name)))
        .collect::<Result<Vec<_>>>()?;

    // Each section and symbol must be defined only once
    let mut defined = HashSet::new();
    for section in &sections {
        let labels = section.items.iter().filter_map(|item| match item {
            Item::Label(symbol) => Some(symbol),
            Item::Inst(_) => None,
        });
        for symbol in core::iter::once(&section.name).chain(labels) {
            if symbols.get(symbol).is_some() || !defined.insert(symbol.clone()) {
                return Err(BackendError::Duplicate(symbol.clone()));
            }
        }
    }

    // Compute the addresses until nothing moves
    let mut ranges = vec![(0, 0); sections.len()];
    let mut converged = false;
    for _ in 0..MAX_PASSES {
        let mut changed = false;
        let mut cursors = data_end.clone();
        for ((section, placement), range) in sections.iter_mut().zip(&placements).zip(&mut ranges) {
            let start = match *placement {
                Placement::Fixed(addr) => addr,
                Placement::Bank(index) => cursors[index],
            };
            changed |= symbols.set(&section.name, start);

            let mut pc = start;
            for item in section.items.iter_mut() {
                match item {
                    Item::Label(symbol) => changed |= symbols.set(symbol, pc),
                    Item::Inst(inst) => pc += inst.size(pc, &symbols) as Addr,
                }
            }

            changed |= *range != (start, pc);
            *range = (start, pc);
            if let Placement::Bank(index) = *placement {
                cursors[index] = pc;
            }
        }
        if !changed {
            converged = true;
            break;
        }
    }
    if !converged {
        return Err(BackendError::NoConvergence);
    }

    // Encode each section in its bank
    let mut images: Vec<Option<BytesMut>> = map
        .banks
        .iter()
        .map(|bank| {
            (bank.kind == BankKind::Rom)
                .then(|| BytesMut::from(&vec![map.fill; bank.size as usize][..]))
        })
        .collect();

    let mut bank_of = Vec::with_capacity(sections.len());
    for ((section, placement), &(start, end)) in sections.iter().zip(&placements).zip(&ranges) {
        let not_in_rom = || BackendError::NotInRom {
            section: section.name.clone(),
            addr: start,
        };
        let index = match *placement {
            Placement::Bank(index) => index,
            Placement::Fixed(addr) => map
                .banks
                .iter()
                .position(|bank| bank.contains(addr))
                .ok_or_else(not_in_rom)?,
        };
        bank_of.push(index);
        let bank = &map.banks[index];
        check_bank(bank, end)?;
        let image = images[index].as_mut().ok_or_else(not_in_rom)?;

        let mut out = BytesMut::with_capacity((end - start) as usize);
        let mut pc = start;
        for item in &section.items {
            if let Item::Inst(inst) = item {
                let before = out.len();
                inst.encode(pc, &symbols, &mut out)?;
                pc += (out.len() - before) as Addr;
            }
        }
        if pc != end {
            return Err(BackendError::Internal(format!(
                "`{}` was laid out with {} bytes but encoded with {}",
                section.name,
                end - start,
                pc - start
            )));
        }

        let offset = (start - bank.start) as usize;
        image[offset..offset + out.len()].copy_from_slice(&out);
    }

    // Sections of a bank must not overlap (possible with fixed addresses).
    // Distinct banks may share addresses (bank switching).
    let mut order: Vec<usize> = (0..sections.len()).collect();
    order.sort_by_key(|&i| (bank_of[i], ranges[i]));
    for pair in order.windows(2) {
        let (a, b) = (pair[0], pair[1]);
        let empty = |i: usize| ranges[i].0 == ranges[i].1;
        if bank_of[a] == bank_of[b] && ranges[a].1 > ranges[b].0 && !empty(a) && !empty(b) {
            return Err(BackendError::Overlap(
                sections[a].name.clone(),
                sections[b].name.clone(),
            ));
        }
    }

    let banks = map
        .banks
        .iter()
        .zip(images)
        .filter_map(|(bank, image)| {
            image.map(|bytes| BankImage {
                name: bank.name.clone(),
                start: bank.start,
                bytes: bytes.freeze(),
            })
        })
        .collect();

    Ok(Image { banks, symbols })
}

/// Path used in error messages about a section
fn section_path(symbol: &Symbol) -> &Path {
    static EMPTY: std::sync::OnceLock<Path> = std::sync::OnceLock::new();
    match symbol {
        Symbol::Var(path) | Symbol::Func(path) | Symbol::Label(path) => path,
        _ => EMPTY.get_or_init(|| Path::new(Vec::new())),
    }
}

/// Render sections as assembly text (for debugging and tests)
pub fn listing<I: fmt::Display>(sections: &[Section<I>]) -> String {
    let mut out = String::new();
    for section in sections {
        let _ = writeln!(out, "{}:", section.name);
        for item in &section.items {
            let _ = match item {
                Item::Label(symbol) => writeln!(out, "{symbol}:"),
                Item::Inst(inst) => writeln!(out, "    {inst}"),
            };
        }
    }
    out
}
